const DICTS: Record<Lang, Record<string, string>> = { zh, en };

let current: Lang = "zh";

/** 切换当前语言（由 useAppStore 在语言变化时调用） */
export function setLang(lang: Lang): void {
  current = lang;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
}

export function getLang(): Lang {
  return current;
}

/** 按系统语言判断（WebView 的 navigator.language 即反映系统设置） */
export function detectLang(): Lang {
  const nav = typeof navigator === "undefined" ? "" : navigator.language;
  return nav.toLowerCase().startsWith("zh") ? "zh" : "en";
}

/** 把配置里的语言项解析成实际语言：auto = 跟随系统 */
export function resolveLang(pref: LangPref): Lang {
  return pref === "auto" ? detectLang() : pref;
}

/** 翻译：支持 {0} {1} 占位；缺失时回退中文，再不行原样返回 key */
export function t(key: string, params?: (string | number)[]): string {
  const dict = DICTS[current];
  let text = dict[key] ?? zh[key] ?? key;
  if (params !== undefined && params.length > 0) {
    params.forEach((value, index) => {
      text = text.replace(new RegExp(`\\{${index}\\}`, "g"), String(value));
    });
  }
  return text;
}

/**
 * 渲染后端返回的错误文本
 *
 * 后端把"key + 参数"编码成 `key` 或 `key\u{1}参数1\u{1}参数2`（见 lib.rs::encoded），
 * 这里还原并翻译；若收到的是普通文本（例如系统错误），则原样返回。
 */
export function tEncoded(value: string): string {
  if (!value.includes("\u0001")) return t(value);
  const [key, ...params] = value.split("\u0001");
  return t(key, params);
}

/** 供 useMemo/useCallback 依赖使用：语言变了就应重算派生文案 */
export function langVersion(): string {
  return current;
}
